#!/usr/bin/env python3
"""M0 smoke test — proves the ctypes <-> Brain wiring.

No Ren'Py required: runs under plain CPython. It loads libssruntime, binds a
``.ssab``, sets up an animation, advances a few frames, and parses the returned
FrameData FlatBuffer. Success criterion: ``draw_batches`` count > 0.

Usage:
    python tools/m0_smoke.py [path/to/anim.ssab] [animation_name]

With no args it uses ss_assets/overall/Basic.ssab (generated by
scripts/deploy-examples.sh) and auto-selects the first animation in the
.ssab metadata.
"""

from __future__ import annotations

import os
import sys

_HERE = os.path.dirname(os.path.abspath(__file__))
_GAME = os.path.join(os.path.dirname(_HERE), "game")
sys.path.insert(0, os.path.join(_GAME, "spritestudio", "python"))  # import ss_renpy

import ss_renpy  # noqa: E402
ss_renpy.bootstrap_paths()  # put generated bindings + flatbuffers on path

from ss_renpy import ssruntime  # noqa: E402
from ss_renpy.ssab_meta import SsabMeta  # noqa: E402
from ss.runtime.FrameData import FrameData  # noqa: E402  (flatc generated)


def main(argv: list[str]) -> int:
    ssab_path = argv[1] if len(argv) > 1 else os.path.join(
        _GAME, "ss_assets", "overall", "Basic.ssab")
    if not os.path.exists(ssab_path):
        print(f"!! .ssab not found: {ssab_path}")
        return 2

    data = open(ssab_path, "rb").read()
    meta = SsabMeta(data)
    anims = meta.animations()
    print(f"== .ssab: {os.path.basename(ssab_path)} "
          f"(project '{meta.name}', {len(data)} bytes)")
    print(f"   animations ({len(anims)}): "
          + ", ".join(f"{a.name}[{a.total_frame}f@{a.fps}fps]" for a in anims))
    cms = meta.cellmaps()
    print(f"   cellmaps ({len(cms)}): "
          + ", ".join(f"{c.name}->{c.image_path}" for c in cms))

    anim_name = argv[2] if len(argv) > 2 else (anims[0].name if anims else "")
    if not anim_name:
        print("!! no animation to play")
        return 2

    lib = ssruntime.load_library(log=True)
    with ssruntime.SSRuntime(lib) as rt:
        rt.configure(coordinate_system=ssruntime.COORD_Y_DOWN)
        rt.load_ssab_bytes(data)
        if not rt.setup_animation(anim_name):
            print(f"!! setup_animation({anim_name!r}) returned False")
            return 1
        print(f"== setup_animation({anim_name!r}) OK; fps={rt.fps}")
        rt.set_loop(-1)
        rt.play()

        dt = 1.0 / (rt.fps or 60)
        max_batches = 0
        for step in range(5):
            frame_no = rt.update(dt)
            fb = rt.get_frame_data(frame_no)
            if not fb:
                print(f"   step {step}: empty frame data")
                continue
            fd = FrameData.GetRootAs(fb, 0)
            nb = fd.DrawBatchesLength()
            npc = fd.PartsLength()
            max_batches = max(max_batches, nb)
            # peek at the first batch so we exercise the accessor path
            kinds = []
            for b in range(nb):
                batch = fd.DrawBatches(b)
                kinds.append((batch.Kind(), batch.Count(), batch.TextureHash()))
            print(f"   step {step}: frame={frame_no:6.2f} "
                  f"parts={npc:3d} batches={nb} "
                  f"first3_kinds={kinds[:3]}")

        print()
        if max_batches > 0:
            print(f"PASS: wiring confirmed (max draw_batches={max_batches}).")
            return 0
        print("FAIL: draw_batches stayed 0 — wiring incomplete.")
        return 1


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
